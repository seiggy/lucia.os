async page => {
  const base = 'http://127.0.0.1:4175'
  const check = (value, message) => { if (!value) throw new Error(message) }
  await page.request.get(base + '/__fixture?mode=owner')
  await page.goto(base + '/#/')
  await page.reload()
  await page.getByRole('heading', { name: 'Your lab, within reach.' }).waitFor()
  const workspace = () => page.getByRole('navigation', { name: 'Local AI navigation', exact: true })
  for (const width of [320, 390, 820, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await page.getByRole('button', { name: 'Switch workspace, current: Overview' }).click()
    await page.getByRole('dialog').waitFor()
    check(await page.getByRole('dialog').evaluate(element => element.getBoundingClientRect().width <= innerWidth), 'Navigation sheet overflows at ' + width)
    await page.getByRole('navigation', { name: 'Local AI tools', exact: true }).getByRole('link', { name: 'Models', exact: true }).click()
    await page.getByRole('heading', { name: 'Models', exact: true }).waitFor()
    check(await workspace().getByRole('link', { name: 'Models', exact: true }).getAttribute('aria-current') === 'page', 'Models lost its navigation location')
    check(await page.getByRole('heading', { name: 'On your Spark', exact: true }).isVisible(), 'Installed library is not the default model view')
    check(!await page.getByRole('heading', { name: 'Find a model', exact: true }).isVisible(), 'Acquisition still competes with the installed library')
    await workspace().getByRole('link', { name: 'API keys', exact: true }).click()
    await page.getByRole('heading', { name: 'API keys', exact: true }).waitFor()
    check(!await page.getByRole('textbox', { name: 'Name', exact: true }).isVisible(), 'Creation form still precedes the key list')
    await page.getByRole('button', { name: 'New API key', exact: true }).click()
    check(await page.getByRole('textbox', { name: 'Name', exact: true }).evaluate(element => document.activeElement === element), 'New key form did not receive focus')
    await page.getByRole('button', { name: 'Not now', exact: true }).click()
    await page.getByRole('button', { name: 'Find a tool', exact: true }).click()
    await page.getByRole('textbox', { name: 'Search available tools' }).fill('chat')
    await page.getByRole('dialog').getByRole('link', { name: 'Playground', exact: false }).click()
    await page.getByRole('heading', { name: 'Playground', exact: true }).waitFor()
    await page.getByRole('textbox', { name: 'Your message', exact: true }).fill('A draft that stays with me')
    await workspace().getByRole('link', { name: 'Models', exact: true }).click()
    await workspace().getByRole('link', { name: 'Playground', exact: true }).click()
    check(await page.getByRole('textbox', { name: 'Your message', exact: true }).inputValue() === 'A draft that stays with me', 'Sibling navigation discarded the conversation draft')
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Horizontal overflow at ' + width)
    await page.getByRole('link', { name: 'Lucia Home', exact: true }).click()
    await page.getByRole('heading', { name: 'Your lab, within reach.' }).waitFor()
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Find a tool', exact: true }).focus()
  await page.keyboard.press('Control+k')
  await page.getByRole('textbox', { name: 'Search available tools' }).fill('keys')
  check(await page.getByRole('dialog').getByRole('link').count() === 1, 'Tool search did not narrow the navigation')
  await page.keyboard.press('Escape')
  check(await page.getByRole('button', { name: 'Find a tool', exact: true }).evaluate(element => document.activeElement === element), 'Escape did not restore focus to the opener')
  await page.goto(base + '/#/ai')
  await page.getByRole('textbox', { name: 'Your message', exact: true }).fill('Synthetic navigation regression')
  await page.getByRole('button', { name: 'Send message', exact: true }).click()
  await page.getByText('Synthetic authenticated response.', { exact: true }).waitFor()
  await workspace().getByRole('link', { name: 'API keys', exact: true }).click()
  await workspace().getByRole('link', { name: 'Playground', exact: true }).click()
  await page.getByRole('heading', { name: 'Playground', exact: true }).waitFor()
  await page.getByText('Synthetic authenticated response.', { exact: true }).waitFor()
  check(await page.getByText('Synthetic authenticated response.', { exact: true }).isVisible(), 'Sibling navigation lost the in-memory transcript')
  const summary = page.getByText('Model limit, not a memory guarantee', { exact: true })
  await summary.focus()
  await page.keyboard.press('Tab')
  check(await page.evaluate(() => {
    const element = document.activeElement
    const rect = element.getBoundingClientRect()
    const hit = document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2)
    return rect.y >= 130 && rect.bottom <= innerHeight && !!hit && (element === hit || element.contains(hit))
  }), 'Keyboard-focused action is obscured by sticky navigation')
  await page.request.get(base + '/__fixture?mode=member')
  await page.reload()
  await page.getByRole('heading', { name: 'Playground', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Find a tool', exact: true }).click()
  await page.getByRole('textbox', { name: 'Search available tools' }).fill('keys')
  await page.getByText('No matching tools.', { exact: false }).waitFor()
  check(await page.getByRole('dialog').getByRole('link').count() === 0, 'Inference member was offered Owner-only tools')
  await page.keyboard.press('Escape')
  check(await page.getByText('Synthetic authenticated response.', { exact: true }).count() === 0, 'Browser refresh retained conversation content')
  return { responsiveWorkspaceNavigation: true, directSiblingTools: true, searchable: true, roleAware: true, inMemoryDraftAndTranscript: true, safeFocus: true }
}
