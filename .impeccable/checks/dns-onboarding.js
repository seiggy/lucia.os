async page => {
  const base = 'http://127.0.0.1:4175'
  const check = (value, message) => { if (!value) throw new Error(message) }
  await page.request.get(base + '/__fixture?mode=owner')
  await page.goto(base + '/#/settings/domains')
  await page.reload()
  await page.getByRole('heading', { name: 'Connect AdGuard first' }).waitFor()
  await page.getByRole('link', { name: 'Configure AdGuard' }).click()
  await page.getByLabel('API origin').fill('http://192.168.1.230:3000')
  await page.getByLabel('Username', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Password', { exact: true }).fill('synthetic-not-a-real-password')
  check(await page.getByRole('button', { name: 'Verify and save' }).isDisabled(), 'HTTP credentials can be sent without explicit consent')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Verify and save' }).click()
  await page.getByRole('heading', { name: 'Configured connection' }).waitFor()
  check(await page.getByLabel('Password', { exact: true }).inputValue() === '', 'Password remains in the form after saving')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: '.impeccable\\review\\adguard-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '.impeccable\\review\\adguard-mobile.png', fullPage: true })
  await page.getByRole('link', { name: 'Set up DNS & certificates' }).click()
  const tokenHelp = page.locator('details').filter({ has: page.getByText('Create a Cloudflare account API token', { exact: true }) })
  await tokenHelp.getByText('Add policy', { exact: true }).waitFor()
  check(await tokenHelp.getByText('DNS Write — your selected zone only', { exact: true }).isVisible(), 'DNS Write permission instructions are missing')
  check(await tokenHelp.getByText('Zone Read — the same zone only', { exact: true }).isVisible(), 'Zone Read permission instructions are missing')
  check((await tokenHelp.innerText()).includes('change its zone selection from All zones'), 'Default all-zone access is not called out')
  for (const width of [320, 390, 820, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Cloudflare instructions overflow at ' + width)
  }
  await page.screenshot({ path: '.impeccable\\review\\cloudflare-token-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '.impeccable\\review\\cloudflare-token-mobile.png', fullPage: true })
  await page.getByLabel('Cloudflare account ID').fill('a'.repeat(32))
  await page.getByLabel('Account API token').fill('cfat_synthetic_account_token')
  await page.getByRole('button', { name: 'Verify account and continue' }).click()
  await page.getByLabel('Cloudflare domain').selectOption('a'.repeat(32))
  await page.getByLabel('Local subdomain').fill('homelab')
  await page.getByText('Customize service URLs', { exact: true }).click()
  await page.getByLabel('Lucia URL', { exact: true }).fill('https://portal.example.com')
  await page.getByLabel('Authentik URL', { exact: true }).fill('https://identity.homelab.example.com')
  await page.getByLabel('Spark name', { exact: true }).fill('atlas')
  check(await page.getByLabel('Lucia URL', { exact: true }).inputValue() === 'https://portal.example.com', 'Renaming Spark silently overwrote the custom Lucia URL')
  check(await page.getByLabel('Spark alias URL', { exact: true }).inputValue() === 'https://atlas.homelab.example.com', 'Unmodified suggested Spark URL did not follow its name')
  await page.getByLabel('ACME contact email').fill('owner@example.com')
  await page.getByRole('button', { name: 'Review DNS setup' }).click()
  await page.getByRole('heading', { name: 'Review the exact changes' }).waitFor()
  check(await page.getByRole('button', { name: 'Set up DNS & certificates' }).isDisabled(), 'Setup did not require consent')
  await page.getByRole('checkbox').nth(0).check()
  check(await page.getByRole('button', { name: 'Set up DNS & certificates' }).isDisabled(), 'Terms acceptance bypassed DNS approval')
  await page.getByRole('checkbox').nth(1).check()
  for (const width of [320, 390, 820, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'DNS onboarding overflow at ' + width)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: '.impeccable\\review\\domains-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '.impeccable\\review\\domains-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Set up DNS & certificates' }).click()
  await page.getByText('Synthetic task accepted; no live DNS changes.', { exact: true }).waitFor({ timeout: 10000 })
  check(await page.evaluate(() => !JSON.stringify(localStorage).includes('cfat_synthetic') && !JSON.stringify(localStorage).includes('synthetic-not-a-real-password')), 'Provider credentials reached browser storage')
  return { adguardPrerequisite: true, httpExplicitConsent: true, passwordCleared: true, customUrlsPreserved: true, termsAndDnsConsent: true, responsive: true, noBrowserCredentialPersistence: true }
}
