async page => {
  const base = 'http://127.0.0.1:4175'
  const check = (value, message) => { if (!value) throw new Error(message) }
  await page.request.get(base + '/__fixture?mode=owner')
  await page.goto(base + '/#/ai/keys')
  await page.reload()
  await page.getByRole('heading', { name: 'API keys', exact: true }).waitFor()
  await page.getByRole('button', { name: 'New API key', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Synthetic client')
  await page.getByRole('button', { name: 'Create inference key', exact: true }).click()
  await page.getByRole('heading', { name: 'Copy this key now.' }).waitFor()
  const secret = await page.getByLabel('New inference API key').inputValue()
  check(secret.startsWith('lucia_inf_'), 'Created key is missing')
  check(await page.evaluate(value => !Object.values(localStorage).some(item => item.includes(value)), secret), 'Secret reached local storage')
  await page.getByRole('button', { name: 'I have saved it' }).click()
  check(await page.getByLabel('New inference API key').count() === 0, 'Dismissed secret remains visible')
  await page.getByRole('button', { name: 'Revoke Synthetic client' }).click()
  await page.getByRole('button', { name: 'Revoke key', exact: true }).click()
  await page.getByText('No application keys have been created yet.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'New API key', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Secret cleanup fixture')
  await page.getByRole('button', { name: 'Create inference key', exact: true }).click()
  await page.getByRole('heading', { name: 'Copy this key now.' }).waitFor()
  await page.getByRole('button', { name: 'Revoke Secret cleanup fixture' }).click()
  await page.getByRole('button', { name: 'Revoke key', exact: true }).click()
  await page.getByText('No application keys have been created yet.', { exact: true }).waitFor()
  check(await page.getByLabel('New inference API key').count() === 0, 'Revoked secret remains available to copy')
  await page.goto(base + '/#/ai/models/find')
  await page.getByRole('heading', { name: 'Find models', exact: true }).waitFor()
  await page.locator('.provider-connection > summary').click()
  await page.getByText('Anonymous access.', { exact: false }).waitFor()
  await page.getByLabel('Hugging Face access token', { exact: true }).fill('hf_syntheticfixture')
  await page.getByRole('button', { name: 'Save access token', exact: true }).click()
  await page.getByText('Authenticated access as synthetic-user.', { exact: true }).waitFor()
  check(await page.getByLabel('Hugging Face access token', { exact: true }).inputValue() === '', 'Provider token remains in the form after saving')
  await page.getByLabel('Search Hugging Face', { exact: true }).fill('fixture')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await page.getByRole('button', { name: 'fixture/chat-GGUF', exact: false }).click()
  await page.getByLabel('File and quantization', { exact: true }).selectOption('fixture-Q4_K_M.gguf')
  await page.getByRole('heading', { name: 'Estimated context capacity', exact: true }).waitFor()
  check(await page.getByRole('button', { name: 'Download selected model', exact: true }).isDisabled(), 'Unqualified model downloaded without opt-in')
  await page.getByLabel('I understand that this model/quantization', { exact: false }).check()
  await page.getByRole('button', { name: 'Download selected model', exact: true }).click()
  await page.getByRole('heading', { name: 'Download model?', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Download model', exact: true }).click()
  await page.getByText('Download queued. Its actual state will appear in your library.', { exact: true }).waitFor()
  await page.getByRole('link', { name: 'Installed models', exact: true }).click()
  await page.getByRole('button', { name: 'Unload', exact: true }).click()
  await page.getByRole('heading', { name: 'Unload LLM?', exact: true }).waitFor()
  await page.route('**/api/host/status', route => route.fulfill({
    status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Synthetic host status failure.' } }),
  }))
  await page.getByText('Synthetic host status failure.', { exact: true }).waitFor({ timeout: 15000 })
  check(await page.getByRole('button', { name: 'Unload LLM', exact: true }).isDisabled(), 'Pending model confirmation ignored unavailable host status')
  await page.getByRole('button', { name: 'Not now', exact: true }).click()
  await page.unroute('**/api/host/status')
  for (const width of [320, 390, 768, 1280]) {
    await page.setViewportSize({ width, height: 900 })
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Management overflow at ' + width)
  }
  await page.locator('main').evaluate(element => element.scrollIntoView())
  return { oneTimeSecret: true, noBrowserPersistence: true, revoked: true, revokedSecretCleared: true, unavailableConfirmationBlocked: true, providerTokenCleared: true, quantizationPreview: true, downloadQueuedNotCompleted: true, responsive: true }
}
